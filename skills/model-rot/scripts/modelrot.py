import datetime as dt
import html
import json
import os
import re
import sys
import time
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path

SOURCES = {
    "anthropic": "https://platform.claude.com/docs/en/about-claude/model-deprecations.md",
    "openai": "https://developers.openai.com/api/docs/deprecations",
    "gemini": "https://ai.google.dev/gemini-api/docs/deprecations.md.txt",
    # GitHub Copilot model *display names*, as pinned in VS Code prompt/agent/chat-mode files. The docs table lags
    # the changelog (2026-11-17: the 2026-12-14 retirements were only in the changelog), so both are read.
    "copilot": "https://docs.github.com/api/article/body?pathname=/en/copilot/reference/ai-models/supported-models",
    "copilot-changelog": "https://github.blog/changelog/feed/",
    # Cloudflare Workers AI announces model removals only as changelog posts ("Models deprecated on <date>").
    "cloudflare": "https://developers.cloudflare.com/changelog/rss/index.xml",
}
CF_ID = re.compile(r"@(?:cf|hf)/[\w.-]+/[\w.-]*[\w]")
COPILOT_FILES = (".prompt.md", ".agent.md", ".chatmode.md")
CACHE = Path(os.environ.get("MODEL_ROT_CACHE", Path.home() / ".cache" / "model-rot"))
TODAY = dt.date.today()
MONTHS = {m: i for i, m in enumerate(["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"], 1)}
ID_RX = re.compile(r"(?<![\w./-])((?:claude|gpt|chatgpt|gemini|text-embedding|dall-e|whisper|imagen|veo|tts|davinci|babbage|"
                   r"computer-use|codex|omni-moderation|text-moderation|sora|lyria|embedding|text-davinci|text-search|"
                   r"code-davinci|code-cushman|curie|ada|o[1-9])(?:-[\w.]+)*)(?![\w/-])")
API_PATTERNS = [  # (name as it appears on the provider page, code regex)
    ("Assistants API", re.compile(r"\bbeta\.(assistants|threads)\b|api\.openai\.com/v1/(assistants|threads)\b|OpenAIAssistant")),
]
SCAN_EXT = {".py", ".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx", ".go", ".rs", ".java", ".kt", ".rb", ".php", ".cs",
            ".json", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".env", ".md", ".mdx", ".txt", ".sh"}
SKIP_DIRS = {".git", "node_modules", "dist", "build", ".venv", "venv", "__pycache__", ".next", "vendor", "site-packages"}
LOCKFILES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock", "Cargo.lock", "worker-configuration.d.ts"}
# worker-configuration.d.ts is generated by `wrangler types` and declares every Workers AI model: not usage


@dataclass
class Entry:
    id: str
    provider: str
    date: dt.date | None = None
    earliest: bool = False       # "not sooner than" / "earliest possible"
    replacement: str = ""
    aliased: bool = False
    alias_date: dt.date | None = None
    source: str = ""

    def status(self, today=None) -> str:
        today = today or TODAY
        if self.aliased and (self.alias_date is None or self.alias_date <= today):
            return "aliased"
        if self.date is None:
            return "aliasing" if self.aliased else "no date"
        if self.date <= today:
            return "retired"
        return "aliasing" if self.aliased else "retiring"


@dataclass
class Hit:
    file: str
    line: int
    match: str
    entry: Entry | None
    kind: str = "model"            # model / api
    note: str = ""


# ---------------------------------------------------------------- fetching

def fetch(provider: str, refresh=False, max_age=86400) -> tuple[str, float]:
    CACHE.mkdir(parents=True, exist_ok=True)
    p = CACHE / f"{provider}.txt"
    if p.exists() and not refresh and time.time() - p.stat().st_mtime < max_age:
        return p.read_text(), p.stat().st_mtime
    req = urllib.request.Request(SOURCES[provider], headers={"User-Agent": "model-rot/0.1"})
    with urllib.request.urlopen(req, timeout=30) as r:
        text = r.read().decode("utf-8", "replace")
    p.write_text(text)
    return text, time.time()


# ---------------------------------------------------------------- parsing

def parse_date(s: str) -> tuple[dt.date | None, bool]:
    s = s.strip()
    earliest = bool(re.search(r"not sooner than|earliest|no earlier than", s, re.I))
    m = re.search(r"(\d{4})-(\d{2})-(\d{2})", s)
    if m:
        return dt.date(int(m.group(1)), int(m.group(2)), int(m.group(3))), earliest
    m = re.search(r"([A-Za-z]{3})[a-z]*\.?\s+(\d{1,2}),?\s+(\d{4})", s)
    if m and m.group(1).lower()[:3] in MONTHS:
        return dt.date(int(m.group(3)), MONTHS[m.group(1).lower()[:3]], int(m.group(2))), earliest
    return None, earliest


def ids_in(cell: str) -> list[str]:
    # drop prose parentheticals ("(… no longer available …; routes to …)"), keep ID lists like "GPT-4o (gpt-4o-…)"
    cell = re.sub(r"\([^)]*(?:no longer|rout|effective|available|shutting)[^)]*\)", " ", cell, flags=re.I)
    ticked = re.findall(r"`([\w.:@-]+)`", cell)
    if ticked:
        return ticked
    return [m.group(1) for m in ID_RX.finditer(cell)]


def rows_to_entries(header: list[str], rows: list[list[str]], provider: str, src: str) -> list[Entry]:
    h = [c.lower() for c in header]
    id_col = next((i for i, c in enumerate(h) if "model" in c or "name" in c or "affected" in c or "agent" in c), None)
    date_col = next((i for i, c in enumerate(h) if "retire" in c or "shutdown" in c), None)
    rep_col = next((i for i, c in enumerate(h) if "replacement" in c), None)
    state_col = next((i for i, c in enumerate(h) if c.strip() in ("current state", "state", "status")), None)
    out = []
    if id_col is None or date_col is None:
        return out
    for r in rows:
        if len(r) <= max(id_col, date_col):
            continue
        date, earliest = parse_date(r[date_col])
        if state_col is not None and state_col < len(r) and r[state_col].strip().lower() == "active":
            date = None   # an active model's "not sooner than" date is a promise, not an announced retirement
        rep = r[rep_col] if rep_col is not None and rep_col < len(r) else ""
        aliased = bool(re.search(r"\brout(?:e|es|ed|ing)\b.*\bto\b|alias", rep, re.I))
        alias_date = None
        if aliased:
            m = re.search(r"effective\s+([A-Za-z]+\s+\d{1,2},?\s+\d{4})", rep, re.I)
            alias_date = parse_date(m.group(1))[0] if m else None
        ids = ids_in(r[id_col])
        cell = r[id_col].strip()
        if not ids and cell:
            # a feature/API row ("Assistants API") keeps its name; otherwise the first word is the ID
            first = cell.split()[0].strip("`,")
            # the first word is an ID only if it looks like one: "Agent Builder" must not turn every "agent" into a hit
            plain_word = re.fullmatch(r"[A-Za-z]+", first) and not ID_RX.fullmatch(first.lower())
            ids = [cell] if re.search(r"\bAPI\b|endpoint", cell) or plain_word else [first]
        for i in ids:
            out.append(Entry(i, provider, date, earliest, re.sub(r"\s+", " ", rep)[:120], aliased, alias_date, src))
    return out


def parse_markdown_tables(text: str, provider: str, src: str) -> list[Entry]:
    out, block = [], []
    for line in text.splitlines() + [""]:
        if line.strip().startswith("|"):
            block.append(line)
            continue
        if len(block) >= 2:
            cells = [[c.strip() for c in l.strip().strip("|").split("|")] for l in block]
            body = [c for c in cells[1:] if not all(re.fullmatch(r":?-+:?", x) for x in c if x)]
            out += rows_to_entries(cells[0], body, provider, src)
        block = []
    return out


def parse_markdoc_tables(text: str, provider: str, src: str) -> list[Entry]:
    out = []
    for blk in re.findall(r"\{%\s*table\s*%\}(.*?)\{%\s*/table\s*%\}", text, re.S):
        rows = []
        for part in re.split(r"^\s*---\s*$", blk, flags=re.M):
            cells, cur = [], None
            for line in part.splitlines():
                m = re.match(r"^\s*\*\s?(.*)$", line)
                if m:
                    if cur is not None:
                        cells.append(cur.strip())
                    cur = m.group(1)
                elif cur is not None and line.strip():
                    cur += " " + line.strip()
            if cur is not None:
                cells.append(cur.strip())
            if cells:
                rows.append(cells)
        if len(rows) >= 2:
            out += rows_to_entries(rows[0], rows[1:], provider, src)
    return out


def parse_html_tables(text: str, provider: str, src: str) -> list[Entry]:
    out = []
    for tbl in re.findall(r"<table[^>]*>(.*?)</table>", text, re.S):
        rows = []
        for tr in re.findall(r"<tr[^>]*>(.*?)</tr>", tbl, re.S):
            cells = [re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", c))).strip()
                     for c in re.findall(r"<t[hd][^>]*>(.*?)</t[hd]>", tr, re.S)]
            if cells:
                rows.append(cells)
        if len(rows) >= 2:
            out += rows_to_entries(rows[0], rows[1:], provider, src)
    return out


def copilot_key(name: str) -> str:
    """'Claude Sonnet 4.5 (copilot)', 'claude-sonnet-4.5', 'GPT-5.4' -> one comparable key."""
    n = re.sub(r"\[\^[^\]]*\]|[*`\u2020\u2021]", "", name)
    n = re.sub(r"\((?:copilot|preview)\)", "", n, flags=re.I)
    return "copilot:" + re.sub(r"[\s_-]+", " ", n.strip().strip("\"'")).lower().strip()


def _copilot_rows(rows: list[list[str]], src: str) -> list[Entry]:
    out = []
    for r in rows:
        if len(r) < 2 or not r[0].strip():
            continue
        d, _ = parse_date(r[1])
        if d is None:
            continue
        caveat = " (exceptions apply: see source)" if re.search(r"[*\u2020\u2021]|\[\^", r[0]) else ""
        rep = (r[2].strip() if len(r) > 2 else "") + caveat
        out.append(Entry(copilot_key(r[0]), "copilot", d, False, rep, False, None, src))
    return out


def parse_copilot_docs(text: str, provider: str, src: str) -> list[Entry]:
    i = text.find("Model retirement history")
    if i < 0:
        return []
    rows = []
    for line in text[i:].splitlines()[1:]:
        if line.startswith("#"):
            break
        if line.strip().startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells and not all(re.fullmatch(r":?-*:?", c) for c in cells):
                rows.append(cells)
    return _copilot_rows([r for r in rows if not r[0].lower().startswith("model name")], src)


def parse_copilot_changelog(text: str, provider: str, src: str) -> list[Entry]:
    out = []
    for item in re.findall(r"<item>(.*?)</item>", text, re.S):
        title = html.unescape(re.sub(r"<!\[CDATA\[|\]\]>", "", (re.search(r"<title>(.*?)</title>", item, re.S) or ["", ""])[1]))
        if not re.search(r"copilot", title, re.I) or not re.search(r"deprecat|retire", title, re.I):
            continue
        link = (re.search(r"<link>(.*?)</link>", item) or [None, src])[1].strip()
        body = re.sub(r"<sup>(.*?)</sup>", r"[^\1]", html.unescape(item), flags=re.S)   # footnote markers
        for tbl in re.findall(r"<table[^>]*>(.*?)</table>", body, re.S):
            rows = [[re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", c))).strip()
                     for c in re.findall(r"<t[hd][^>]*>(.*?)</t[hd]>", tr, re.S)]
                    for tr in re.findall(r"<tr[^>]*>(.*?)</tr>", tbl, re.S)]
            if not rows:
                continue
            mi = next((i for i, c in enumerate(rows[0]) if re.search(r"model", c, re.I)), None)
            di = next((i for i, c in enumerate(rows[0]) if re.search(r"date", c, re.I)), None)
            ai = next((i for i, c in enumerate(rows[0]) if re.search(r"alternative|replacement", c, re.I)), None)
            if mi is None or di is None:
                continue
            out += _copilot_rows([[r[mi], r[di], r[ai] if ai is not None and ai < len(r) else ""]
                                  for r in rows[1:] if len(r) > max(mi, di)], link)
    return out


def parse_cloudflare_changelog(text: str, provider: str, src: str) -> list[Entry]:
    """Workers AI deprecation posts: IDs listed under 'Models deprecated on <Month D, YYYY>' headings.
    IDs before the first such heading (recommended replacements) are not deprecations."""
    out = []
    for item in re.findall(r"<item>(.*?)</item>", text, re.S):
        title = html.unescape((re.search(r"<title>(.*?)</title>", item, re.S) or ["", ""])[1])
        if "workers ai" not in title.lower() or not re.search(r"deprecat|retir|sunset|remov|end of life", title, re.I):
            continue
        link = (re.search(r"<link>(.*?)</link>", item) or [None, src])[1].strip()
        body = re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", html.unescape(item))))
        parts = re.split(r"Models deprecated on ([A-Z][a-z]+ \d{1,2},? \d{4})", body)
        for date_s, seg in zip(parts[1::2], parts[2::2]):
            d, _ = parse_date(date_s)
            # the list ends at the next non-deprecation section ("Variants that remain active", "Recommended …")
            seg = re.split(r"(?i)\b(?:remain(?:s|ing)? (?:active|available)|recommended|for the full list|still available|"
                           r"not affected|unaffected)\b", seg, maxsplit=1)[0]
            arrows = dict(re.findall(rf"({CF_ID.pattern})\s*(?:→|->)\s*({CF_ID.pattern})", seg))
            for mid in dict.fromkeys(CF_ID.findall(seg)):
                if mid in arrows.values():
                    continue                       # a replacement, not a deprecated model
                out.append(Entry(mid.lower(), "cloudflare", d, False, arrows.get(mid, "").strip(), False, None, link))
    return out


PARSERS = {"anthropic": parse_markdown_tables, "openai": parse_html_tables, "gemini": parse_markdoc_tables,
           "copilot": parse_copilot_docs, "copilot-changelog": parse_copilot_changelog,
           "cloudflare": parse_cloudflare_changelog}


def load_db(refresh=False, copilot=True) -> tuple[dict[str, Entry], dict[str, str]]:
    db: dict[str, Entry] = {}
    meta: dict[str, str] = {}
    for prov, url in SOURCES.items():
        if prov.startswith("copilot") and not copilot:
            continue
        try:
            text, ts = fetch(prov, refresh)
        except Exception as e:  # noqa: BLE001 - report and continue with other providers
            meta[prov] = f"unavailable ({e.__class__.__name__})"
            continue
        entries = PARSERS[prov](text, prov, url)
        for e in entries:
            key = e.id.lower()
            old = db.get(key)
            # keep the most informative row: one with a date beats one without
            if old is None or (old.date is None and e.date is not None):
                db[key] = e
        meta[prov] = f"{len(entries)} rows, fetched {dt.datetime.fromtimestamp(ts):%Y-%m-%d %H:%M}"
    for key, e in list(db.items()):   # undated aliases of dated snapshots: claude-x-20250514 -> claude-x, -latest, -0
        m = re.match(r"^(.*)-(\d{8})$", key)
        if m:
            for alias in (m.group(1), m.group(1) + "-latest", m.group(1) + "-0"):
                db.setdefault(alias, e)
    return db, meta


# ---------------------------------------------------------------- scanning

def normalize(model: str) -> list[str]:
    """Candidate DB keys for an ID found in code (provider prefixes, Bedrock/Vertex forms)."""
    m = model.lower()
    cands = [m]
    m2 = re.sub(r"^(?:[a-z]{2,6}\.)?anthropic\.", "", m)                   # Bedrock (us./eu./apac./au./jp./global.)
    m2 = re.sub(r"-v\d+(?::\d+)?$", "", m2)
    m2 = re.sub(r"@(\d{8})$", r"-\1", m2)                                 # Vertex claude-x@20250514
    m2 = re.sub(r"-v\d+-(\d{8})$", r"-\1", m2)                            # Vertex claude-3-5-sonnet-v2@20241022
    if m2 != m:
        cands.append(m2)
    return cands


SCAN_EXT |= {".ipynb", ".tf", ".html", ".vue", ".svelte", ".properties", ".xml", ".sql", ".swift", ".dart", ".scala"}
TOKEN = re.compile(r"[A-Za-z0-9][\w.@:/-]*")          # linear: one greedy class, no backtracking
BARE_O = re.compile(r"^o[1-9](?:-[a-z]+)?$")
MAX_BYTES = 5_000_000


def iter_files(root: Path, include_docs: bool):
    if root.is_file():
        yield root
        return
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in sorted(filenames):
            p = Path(dirpath) / name
            suf = p.suffix.lower()
            if name in LOCKFILES:
                continue
            if suf not in SCAN_EXT and not name.startswith(".env"):
                continue
            if not include_docs and suf in (".md", ".mdx", ".txt") and not name.lower().endswith(COPILOT_FILES):
                continue
            yield p


def lookup(token: str, db: dict[str, Entry]) -> Entry | None:
    return next((db[c] for c in normalize(token) if c in db), None)


def _yaml_scalar(v: str) -> str:
    v = re.split(r"\s+#", v, maxsplit=1)[0].strip()
    return v.strip("\"'").strip()


def copilot_frontmatter_hits(rel: str, text: str, db: dict[str, Entry]) -> list[Hit]:
    """`model:` in a VS Code prompt/agent/chat-mode file: scalar, inline [list], block list or folded scalar."""
    lines = text.lstrip("\ufeff").splitlines()
    if not lines or lines[0].strip() != "---":
        return []
    hits, mode = [], ""          # mode: "list" after `model:` with no value, "fold" after `model: >` / `|`
    for n, line in enumerate(lines[1:], 2):
        if line.strip() == "---":
            break
        names: list[str] = []
        m = re.match(r"^model\s*:(.*)$", line)
        if m:
            val = re.split(r"\s+#", m.group(1), maxsplit=1)[0].strip()
            if not val:
                mode = "list"
                continue
            if re.fullmatch(r"[>|][+-]?", val):
                mode = "fold"
                continue
            mode = ""
            names = [_yaml_scalar(x) for x in val.strip("[]").split(",")] if val.startswith("[") else [_yaml_scalar(val)]
        elif mode and (not line.strip() or line.lstrip().startswith("#")):
            continue                                   # blank or comment lines don't end the value
        elif mode == "list" and (m2 := re.match(r"^\s*-\s*(.+)$", line)):
            names = [_yaml_scalar(m2.group(1))]
        elif mode == "fold" and line[:1] in (" ", "\t"):
            names, mode = [_yaml_scalar(line)], ""
        else:
            mode = ""
            continue
        for name in filter(None, names):
            ent = db.get(copilot_key(name))
            if ent:
                hits.append(Hit(rel, n, name, ent, "model", "GitHub Copilot model name"))
    return hits


def scan(root: Path, db: dict[str, Entry], include_docs=True) -> list[Hit]:
    hits = []
    base = root if root.is_dir() else root.parent
    for p in iter_files(root, include_docs):
        try:
            if p.stat().st_size > MAX_BYTES:
                continue
            data = p.read_bytes()
        except OSError:
            continue
        if b"\0" in data[:8192]:
            continue
        rel = str(p.relative_to(base))
        skip_lines: set[int] = set()
        if p.name.lower().endswith(COPILOT_FILES):
            ch = copilot_frontmatter_hits(rel, data.decode("utf-8", "replace"), db)
            hits += ch
            skip_lines = {h.line for h in ch}   # a Copilot display name, not an API ID with another schedule
        for n, line in enumerate(data.decode("utf-8", "replace").splitlines(), 1):
            if n in skip_lines:
                continue
            low = line.lower()
            for m in CF_ID.finditer(line):
                if (ent := db.get(m.group(0).lower())):
                    hits.append(Hit(rel, n, m.group(0), ent, "model", "Cloudflare Workers AI"))
            line = CF_ID.sub(" ", line) if "@" in line else line   # its path parts are not other providers' IDs
            for m in TOKEN.finditer(line):
                whole = m.group(0).strip(".:-/")
                # try the whole token (Bedrock "us.anthropic.claude-…-v1:0") and its / and : parts
                # ("openai/gpt-5", "models/gemini-2.0-flash:generateContent", "ft:gpt-4o-mini-…:org::x")
                parts = [whole] + [x for x in re.split(r"[/:]", whole) if x]
                for part in dict.fromkeys(parts):
                    part = part.strip(".-")
                    if not part or part != part.lower():
                        continue   # API model IDs are lowercase; "GPT-4" is a display label
                    if BARE_O.match(part):
                        ctx = line[max(0, m.start() - 1):m.end() + 1]
                        if not (re.search(r"[\"']", ctx) or "model" in low):
                            continue   # `o3 = 4` is a variable, not the o3 model
                    ent = lookup(part, db)
                    if ent:
                        note = ("Bedrock/Vertex ID: those platforms keep their own schedules"
                                if normalize(part)[-1] != part.lower() else "")
                        hits.append(Hit(rel, n, part, ent, "model", note))
                        break
            for name, rx in API_PATTERNS:
                if rx.search(line):
                    hits.append(Hit(rel, n, name, db.get(name.lower()), "api"))
    return hits


# ---------------------------------------------------------------- CLI

ORDER = {"retired": 0, "aliased": 1, "retiring": 2, "aliasing": 3, "no date": 4, "unknown": 5}


def describe(e: Entry | None, today=None) -> str:
    if e is None:
        return "unknown"
    s = e.status(today)
    d = (f"not sooner than {e.date}" if e.earliest else str(e.date)) if e.date else ""
    rep = f" → {e.replacement}" if e.replacement and not e.aliased else ""
    if s == "retired":
        return f"retired {d}: requests fail{rep}"
    if s == "retiring":
        days = (e.date - (today or TODAY)).days
        return f"retiring {d} (in {days} days){rep}"
    if s in ("aliased", "aliasing"):
        when = f" from {e.alias_date}" if e.alias_date else ""
        return f"silently aliased{when}: {e.replacement}"
    return "no retirement date announced"


def render(hits: list[Hit], meta: dict[str, str], root: Path, days: int) -> str:
    groups: dict[str, list[Hit]] = {}
    for h in hits:
        groups.setdefault(h.entry.status() if h.entry else "unknown", []).append(h)
    L = [f"# model-rot report: {root.name}", "", "Sources (official pages, parsed live): " +
         "; ".join(f"[{p}]({SOURCES[p]}) {m}" for p, m in meta.items()), ""]
    def soon_date(h):
        d = h.entry.alias_date or h.entry.date if h.entry else None
        return d is not None and (d - TODAY).days <= days
    soon = [h for h in groups.get("retiring", []) + groups.get("aliasing", []) if soon_date(h)]
    L.append(f"**{len(groups.get('retired', []))} retired** · **{len(groups.get('aliased', []))} silently aliased** · "
             f"**{len(soon)} retiring or aliasing within {days} days** · "
             f"{len(groups.get('retiring', [])) + len(groups.get('aliasing', [])) - len(soon)} later · "
             f"{len(groups.get('no date', []))} with no date")
    for st in sorted(groups, key=lambda s: ORDER.get(s, 9)):
        if st == "no date":
            continue
        L += ["", f"## {st}", ""]
        seen = set()
        for h in sorted(groups[st], key=lambda h: (h.match, h.file, h.line)):
            key = (h.file, h.line, h.match)
            if key in seen:
                continue
            seen.add(key)
            extra = f" ({h.note})" if h.note else ""
            L.append(f"- `{h.file}:{h.line}` **{h.match}**: {describe(h.entry)}{extra}")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(prog="modelrot", description=__doc__.split("\n\n")[0])
    ap.add_argument("path", nargs="?", default=".")
    ap.add_argument("--days", type=int, default=60, help="'retiring soon' window (default 60)")
    ap.add_argument("--no-docs", action="store_true", help="skip .md/.txt files")
    ap.add_argument("--refresh", action="store_true", help="re-download provider pages")
    ap.add_argument("--lookup", nargs="+", metavar="MODEL", help="just look up model IDs")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--allow-partial", action="store_true", help="continue if a provider page can't be fetched")
    a = ap.parse_args(argv)
    root = Path(a.path).resolve()
    if a.lookup:
        need_copilot = any(x.lower().startswith("copilot:") for x in a.lookup)
    else:
        if not root.exists():
            sys.exit(f"error: {root} does not exist")
        need_copilot = any(p.name.lower().endswith(COPILOT_FILES) for p in iter_files(root, True))
    db, meta = load_db(a.refresh, copilot=need_copilot)
    if a.lookup:
        for mid in a.lookup:
            e = db.get(copilot_key(mid[8:])) if mid.lower().startswith("copilot:") else \
                next((db[c] for c in normalize(mid) if c in db), None)
            print(f"{mid}: {describe(e)}" + (f"  [{e.source}]" if e else ""))
        return
    failed = [p for p, m in meta.items() if m.startswith("unavailable")]
    if failed and not a.allow_partial:
        print(f"error: could not load {', '.join(failed)} deprecation data ({'; '.join(meta[p] for p in failed)}); "
              "results would be incomplete. Retry, or pass --allow-partial.", file=sys.stderr)
        sys.exit(2)   # 2 = sources unavailable, distinct from 1 = retired/retiring models found
    hits = scan(root, db, not a.no_docs)
    if a.json:
        print(json.dumps([{"file": h.file, "line": h.line, "match": h.match, "kind": h.kind,
                           "provider": h.entry.provider if h.entry else "",
                           "status": h.entry.status() if h.entry else "unknown", "detail": describe(h.entry)} for h in hits],
                         indent=1))
    else:
        print(render(hits, meta, root, a.days))
    def due(e):
        d = (e.alias_date or e.date) if e.status() == "aliasing" else e.date
        return d is not None and (d - TODAY).days <= a.days
    bad = any(h.entry and (h.entry.status() in ("retired", "aliased") or
                           (h.entry.status() in ("retiring", "aliasing") and due(h.entry)))
              for h in hits)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
